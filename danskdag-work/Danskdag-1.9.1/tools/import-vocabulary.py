def read_rows(path):
    if path.suffix.lower() == '.json':
        raw = json.loads(path.read_text(encoding='utf-8'))
    else:
        ns = {'s': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
        with zipfile.ZipFile(path) as z:
            strings = []
            if 'xl/sharedStrings.xml' in z.namelist():
                root = ET.fromstring(z.read('xl/sharedStrings.xml'))
                strings = [''.join(t.text or '' for t in si.findall('.//s:t', ns))
                           for si in root.findall('s:si', ns)]
            root = ET.fromstring(z.read('xl/worksheets/sheet1.xml'))
            raw = []
            for row in root.findall('.//s:sheetData/s:row', ns):
                cells = []
                for c in row.findall('s:c', ns):
                    val = c.find('s:v', ns)
                    text = val.text if val is not None else ''
                    if c.get('t') == 's':
                        text = strings[int(text)]
                    elif c.get('t') == 'inlineStr':
                        text = ''.join(t.text or '' for t in c.findall('.//s:t', ns))
                    if text and text.strip():
                        cells.append([c.get('r'), text])
                if cells:
                    raw.append(cells)
    rows = {}
    for cells in raw:
        row_num = int(re.search(r'\d+', cells[0][0]).group())
        rows[row_num] = cells
    return rows


def normalise(text):
    text = unicodedata.normalize('NFC', text).casefold()
    return re.sub(r'\s+', ' ', text).strip().rstrip(' .!?;:,…')


def original(cells):
    # Keep original language labels and every cell; no approximate pronunciation
    # is promoted into the Danish spelling or used as a memory aid.
    return ' | '.join(f'{ref}: {value}' for ref, value in cells)


def tag_for(row, da):
    if row >= 1032 and row <= 1137:
        return 'Ферма и уход за животными'
    if 831 <= row <= 862:
        return 'Сельхозтехника'
    if 879 <= row <= 1018:
        return 'Работа и сборка'
    if 179 <= row <= 188:
        return 'Грамматика'
    if 190 == row:
        return 'Природа'
    if da in {'helbred', 'sundhed', 'betændelse', 'kvalme', 'sår', 'smerte', 'vejrtrækning', 'sygemeldt', 'forebyggelse og behandling'}:
        return 'Здоровье'
    if da in {'høreværn', 'værnemidler', 'personlige værnemidler', 'sikkerhed', 'sikkerhedsafstand', 'nødudgang', 'advarsel', 'farezonen'}:
        return 'Безопасность'
    if any(w in da for w in ('arbejd', 'ansat', 'stilling', 'oplæring', 'udstyr', 'ansvars', 'fagligt', 'overenskomst', 'moment', 'gevind', 'bearbejd', 'beslag')):
        return 'Работа'
    return 'Повседневный датский'


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    rows = read_rows(Path(sys.argv[1]))
    target = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / 'dist/vocabulary.mjs'
    vocab = {}
    consumed = set()
    reviewed_instances = 0
    for block, verified in [(REVIEWED, True), (UNVERIFIED, False)]:
        for line in block.strip().splitlines():
            fields = line.split('|')
            row, da, ru = int(fields[0]), fields[1], fields[2]
            assert row in rows, f'Source worksheet row {row} missing'
            key = normalise(da)
            reviewed_instances += 1
            consumed.add(row)
            note = fields[3] if len(fields) > 3 else ''
            if not verified:
                note = 'Перевод из исходного файла; требует проверки. ' + note
            if row in CORRECTIONS:
                note = (note + ' ' + CORRECTIONS[row]).strip()
            if row in {45, 713}:
                note = (note + ' Грубая/оскорбительная лексика; не используйте в нейтральной речи.').strip()
            if 884 <= row <= 1018:
                note = (note + ' Рабочий контекст; украинский перевод источника передан по-русски.').strip()
            if 179 <= row <= 188 or row in {44, 45, 46, 84, 85, 87, 88, 89, 90, 91, 128, 150}:
                note = (note + ' Украинский перевод источника передан по-русски.').strip()
            if row == 190:
                note = 'Пары разделены по порядку; перевод также находится в строке 191.'
                consumed.add(191)
            if row in {551, 703, 704, 705, 706}:
                note = (note + ' Исходный список разделён на отдельные слова; смысл проверен отдельно.').strip()
            entry = vocab.get(key)
            if entry is None:
                entry = {
                    'id': 'v-' + hashlib.sha256(key.encode()).hexdigest()[:12],
                    'da': da, 'ru': ru, 'note': '', 'association': '',
                    'exampleDa': '', 'exampleRu': '', 'tag': tag_for(row, da),
                    'source': 'file', 'sourceRows': [], 'verified': verified,
                    'original': '',
                }
                vocab[key] = entry
            elif entry['ru'] != ru:
                raise AssertionError(f'Conflicting reviewed meanings for {da}: {entry["ru"]!r} / {ru!r}')
            entry['verified'] = entry['verified'] and verified
            if row not in entry['sourceRows']:
                entry['sourceRows'].append(row)
                entry['original'] += ('\n' if entry['original'] else '') + original(rows[row])
            if note and note not in entry['note']:
                entry['note'] += (' ' if entry['note'] else '') + note
    # The separate translation rows of paired source notes are accounted for.
    paired = {190: [191], 551: [553], 703: [706], 704: [708], 705: [709], 706: [710],
              809: [810], 867: [868], 1020: [1022], 1103: [1104], 1105: [1106],
              1117: [1118], 1121: [1122], 1123: [1124]}
    primary_rows = {entry['id']: set(entry['sourceRows']) for entry in vocab.values()}
    for row, translated_rows in paired.items():
        for entry in vocab.values():
            if row in primary_rows[entry['id']]:
                for tr in translated_rows:
                    if tr in rows and tr not in entry['sourceRows']:
                        entry['sourceRows'].append(tr)
                        entry['original'] += '\n' + original(rows[tr])
                        consumed.add(tr)
    for line in ENRICHMENT.strip().splitlines():
        da, association, ex_da, ex_ru = line.split('|')
        entry = vocab[normalise(da)]
        assert entry['verified']
        entry.update(association=association, exampleDa=ex_da, exampleRu=ex_ru)
    # Clearly identifiable source headings/dividers do not become flashcards.
    headings = {322, 883, 901, 918, 932, 943, 953, 960, 966, 972, 979, 985, 994,
                1002, 1008, 1014, 1095}
    needs_review = [{'original': original(rows[42]), 'note': 'Список деревьев разобран частично. Неясная пара Trans / Транс не импортирована: написание и значение требуют проверки.', 'sourceRows': [42]}]
    skipped = []
    # Treatment directions/doses, including surrounding therapeutic dialogue,
    # are deliberately retained only in the review collection.
    clinical_rows = {1092, 1096, 1098, 1107, 1108, 1109, 1110, 1111, 1112, 1113,
                     1114, 1115, 1116, 1119, 1120, 1140, 1141, 1142, 1143, 1144,
                     1146, 1147, 1148}
    for row, cells in rows.items():
        if row in consumed:
            continue
        if row in headings:
            skipped.append(row)
            continue
        text = original(cells)
        if row in clinical_rows:
            note = 'Медицинская/ветеринарная инструкция, дозировка или связанный лечебный диалог из файла. Сохранено только для просмотра; не является учебным заданием или рекомендацией.'
        elif not re.search(r'[A-Za-zÆØÅæøå]', ' '.join(v for _, v in cells)):
            note = 'В записи нет надёжного датского написания: кириллическая заметка или приблизительное произношение. Восстановление без подтверждения не выполнялось.'
        else:
            note = 'Неоднозначная, неполная или ошибочная исходная запись. Требуется проверка датского написания и соответствия перевода; исключено из упражнений.'
        needs_review.append({'original': text, 'note': note, 'sourceRows': [row]})
    result = sorted(vocab.values(), key=lambda e: (min(e['sourceRows']), e['id']))
    for entry in result:
        entry['sourceRows'].sort()
    summary = {
        'sourceRows': len(rows), 'imported': len(result),
        'duplicatesMerged': reviewed_instances - len(result),
        'needsReview': len(needs_review), 'skipped': len(skipped),
        'verified': sum(e['verified'] for e in result),
        'unverified': sum(not e['verified'] for e in result),
        'enriched': sum(bool(e['association'] and e['exampleDa'] and e['exampleRu']) for e in result),
        'sourceFile': 'Збережені переклади.xlsx',
        'skippedRows': skipped,
        'countingNote': 'sourceRows — непустые строки листа; imported — уникальные словарные записи; duplicatesMerged — объединённые повторные словарные вхождения. Списки могут давать несколько слов из одной строки. needsReview не входит в imported; непроверенные словарные записи входят в imported, но не в обучение.',
    }
    assert len({e['id'] for e in result}) == len(result)
    assert len({normalise(e['da']) for e in result}) == len(result)
    assert all(e['da'] and e['ru'] and re.search(r'[A-Za-zÆØÅæøå]', e['da']) for e in result)
    assert all(not (set(e['sourceRows']) & clinical_rows) for e in result)
    assert consumed | set(skipped) | {r for e in needs_review for r in e['sourceRows']} == set(rows)
    assert not (consumed & set(skipped))
    assert consumed & {r for e in needs_review for r in e['sourceRows']} == {42}, 'Only the explicitly partial tree-list row may overlap review and import'
    target.parent.mkdir(parents=True, exist_ok=True)
    payload = '// Generated by tools/import-vocabulary.py. Source workbook remains unchanged.\n'
    for name, obj in [('vocabulary', result), ('importSummary', summary), ('needsReview', needs_review)]:
        payload += f'export const {name} = ' + json.dumps(obj, ensure_ascii=False, indent=2) + ';\n\n'
    target.write_text(payload, encoding='utf-8')
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
